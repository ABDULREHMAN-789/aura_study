import 'dart:io';
import 'dart:convert';
import 'package:flutter/foundation.dart';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:aura_study/features/notes/domain/note_model.dart';

class ExportService {
  /// Generate a professionally formatted PDF from a StudyNote
  Future<File> exportAsPdf(StudyNote note) async {
    final pdf = pw.Document();

    // Parse hex color for accent
    final accentColor = _parseNoteColor(note.colorHex);

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(40),
        header: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              // Color accent bar
              pw.Container(
                width: double.infinity,
                height: 4,
                decoration: pw.BoxDecoration(
                  color: accentColor,
                  borderRadius: pw.BorderRadius.circular(2),
                ),
              ),
              pw.SizedBox(height: 16),
              // Title
              pw.Text(
                note.title,
                style: pw.TextStyle(
                  fontSize: 24,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.grey900,
                ),
              ),
              pw.SizedBox(height: 8),
              // Metadata row
              pw.Row(
                children: [
                  _buildMetadataChip('Category: ${note.category}'),
                  pw.SizedBox(width: 8),
                  if (note.tags.isNotEmpty)
                    _buildMetadataChip('Tags: ${note.tags.join(", ")}'),
                ],
              ),
              pw.SizedBox(height: 4),
              pw.Text(
                'Created: ${_formatDate(note.createdAt)} • Updated: ${_formatDate(note.updatedAt)}',
                style: pw.TextStyle(
                  fontSize: 9,
                  color: PdfColors.grey500,
                  fontStyle: pw.FontStyle.italic,
                ),
              ),
              pw.SizedBox(height: 12),
              pw.Divider(color: PdfColors.grey300, thickness: 0.5),
              pw.SizedBox(height: 8),
            ],
          );
        },
        footer: (pw.Context context) {
          return pw.Container(
            alignment: pw.Alignment.centerRight,
            margin: const pw.EdgeInsets.only(top: 16),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.end,
              children: [
                pw.Divider(color: PdfColors.grey300, thickness: 0.5),
                pw.SizedBox(height: 6),
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(
                      'Generated by Aura Study',
                      style: pw.TextStyle(
                        fontSize: 8,
                        color: PdfColors.grey500,
                        fontStyle: pw.FontStyle.italic,
                      ),
                    ),
                    pw.Text(
                      'Page ${context.pageNumber} of ${context.pagesCount}',
                      style: const pw.TextStyle(
                        fontSize: 8,
                        color: PdfColors.grey500,
                      ),
                    ),
                  ],
                ),
              ],
            ),
          );
        },
        build: (pw.Context context) {
          return [
            // Content body — split into paragraphs for proper rendering
            ..._buildContentParagraphs(note.content),
          ];
        },
      ),
    );

    final bytes = await pdf.save();
    final tempDir = await getTemporaryDirectory();
    final fileName = getExportFileName(note, 'pdf');
    final file = File('${tempDir.path}/$fileName');
    await file.writeAsBytes(bytes);

    debugPrint("AURA EXPORT: PDF generated at ${file.path} (${bytes.length} bytes)");
    return file;
  }

  /// Generate a DOCX document from a StudyNote
  Future<File> exportAsDocx(StudyNote note) async {
    // Build a DOCX using raw byte construction
    // cleartec_docx_template requires a template file; instead, we generate
    // a minimal valid DOCX structure using the archive and XML approach
    final docxBytes = _buildDocxBytes(note);

    final tempDir = await getTemporaryDirectory();
    final fileName = getExportFileName(note, 'docx');
    final file = File('${tempDir.path}/$fileName');
    await file.writeAsBytes(docxBytes);

    debugPrint("AURA EXPORT: DOCX generated at ${file.path} (${docxBytes.length} bytes)");
    return file;
  }

  /// Share a generated file via Android system share sheet
  Future<void> shareFile(File file, String fileName) async {
    try {
      await SharePlus.instance.share(
        ShareParams(
          files: [XFile(file.path, name: fileName)],
          subject: 'Aura Study — $fileName',
          text: 'Exported from Aura Study 📚',
        ),
      );
      debugPrint("AURA EXPORT: Share sheet triggered for $fileName");
    } catch (e) {
      debugPrint("AURA EXPORT ERROR: Failed to share: $e");
      rethrow;
    }
  }

  /// Generate a sanitized, timestamped filename
  String getExportFileName(StudyNote note, String extension) {
    final sanitizedTitle = note.title
        .replaceAll(RegExp(r'[^\w\s-]'), '')
        .replaceAll(RegExp(r'\s+'), '_')
        .trim();
    final truncated = sanitizedTitle.length > 40
        ? sanitizedTitle.substring(0, 40)
        : sanitizedTitle;
    final timestamp = DateTime.now().millisecondsSinceEpoch.toString().substring(6);
    return 'Aura_Study_${truncated}_$timestamp.$extension';
  }

  // --- Private Helpers ---

  PdfColor _parseNoteColor(String hexString) {
    try {
      final hex = hexString.replaceAll('0x', '').replaceAll('FF', '');
      final colorInt = int.parse(hex, radix: 16);
      final r = (colorInt >> 16) & 0xFF;
      final g = (colorInt >> 8) & 0xFF;
      final b = colorInt & 0xFF;
      return PdfColor.fromInt(0xFF000000 | (r << 16) | (g << 8) | b);
    } catch (e) {
      return PdfColors.indigo;
    }
  }

  pw.Widget _buildMetadataChip(String text) {
    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 3),
      decoration: pw.BoxDecoration(
        color: PdfColors.grey100,
        borderRadius: pw.BorderRadius.circular(4),
        border: pw.Border.all(color: PdfColors.grey300, width: 0.5),
      ),
      child: pw.Text(
        text,
        style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
      ),
    );
  }

  String _formatDate(DateTime date) {
    final months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
                     'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    return '${months[date.month - 1]} ${date.day}, ${date.year}';
  }

  List<pw.Widget> _buildContentParagraphs(String content) {
    final paragraphs = content.split('\n');
    final widgets = <pw.Widget>[];

    for (final paragraph in paragraphs) {
      final trimmed = paragraph.trim();
      if (trimmed.isEmpty) {
        widgets.add(pw.SizedBox(height: 8));
        continue;
      }

      // Detect markdown-style headers
      if (trimmed.startsWith('# ')) {
        widgets.add(pw.Padding(
          padding: const pw.EdgeInsets.only(top: 12, bottom: 4),
          child: pw.Text(
            trimmed.substring(2),
            style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold),
          ),
        ));
      } else if (trimmed.startsWith('## ')) {
        widgets.add(pw.Padding(
          padding: const pw.EdgeInsets.only(top: 10, bottom: 4),
          child: pw.Text(
            trimmed.substring(3),
            style: pw.TextStyle(fontSize: 15, fontWeight: pw.FontWeight.bold),
          ),
        ));
      } else if (trimmed.startsWith('- ') || trimmed.startsWith('• ')) {
        widgets.add(pw.Padding(
          padding: const pw.EdgeInsets.only(left: 16, top: 2, bottom: 2),
          child: pw.Row(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text('• ', style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold)),
              pw.Expanded(
                child: pw.Text(
                  trimmed.substring(2),
                  style: const pw.TextStyle(fontSize: 11, lineSpacing: 1.4),
                ),
              ),
            ],
          ),
        ));
      } else {
        widgets.add(pw.Padding(
          padding: const pw.EdgeInsets.only(bottom: 4),
          child: pw.Text(
            trimmed,
            style: const pw.TextStyle(fontSize: 11, lineSpacing: 1.5),
          ),
        ));
      }
    }

    return widgets;
  }

  /// Build a minimal valid DOCX file as bytes (Open XML format)
  List<int> _buildDocxBytes(StudyNote note) {
    // Import archive for ZIP creation
    return _DocxBuilder.build(note);
  }
}

/// Minimal DOCX builder using raw ZIP/XML structure
/// DOCX is a ZIP archive containing XML files in Open XML format
class _DocxBuilder {
  static List<int> build(StudyNote note) {
    // We use the archive package which is already a transitive dependency
    // to build a proper DOCX ZIP structure
    final contentXml = _buildDocumentXml(note);
    final relsXml = _buildRelsXml();
    final contentTypesXml = _buildContentTypesXml();
    final wordRelsXml = _buildWordRelsXml();

    // Build ZIP manually using dart:io compression
    return _createDocxZip(contentXml, relsXml, contentTypesXml, wordRelsXml);
  }

  static String _buildDocumentXml(StudyNote note) {
    final escapedTitle = _escapeXml(note.title);
    final escapedCategory = _escapeXml(note.category);
    final escapedTags = _escapeXml(note.tags.join(', '));
    final dateStr = '${note.createdAt.year}-${note.createdAt.month.toString().padLeft(2, '0')}-${note.createdAt.day.toString().padLeft(2, '0')}';

    final contentParagraphs = note.content.split('\n').map((line) {
      final trimmed = line.trim();
      if (trimmed.isEmpty) {
        return '<w:p><w:r><w:t xml:space="preserve"> </w:t></w:r></w:p>';
      }

      String style = '';
      String text = trimmed;

      if (trimmed.startsWith('# ')) {
        style = '<w:pPr><w:pStyle w:val="Heading1"/></w:pPr>';
        text = trimmed.substring(2);
      } else if (trimmed.startsWith('## ')) {
        style = '<w:pPr><w:pStyle w:val="Heading2"/></w:pPr>';
        text = trimmed.substring(3);
      } else if (trimmed.startsWith('- ') || trimmed.startsWith('• ')) {
        text = '• ${trimmed.substring(2)}';
      }

      return '<w:p>$style<w:r><w:t xml:space="preserve">${_escapeXml(text)}</w:t></w:r></w:p>';
    }).join('\n');

    return '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:wpc="http://schemas.microsoft.com/office/word/2010/wordprocessingCanvas"
  xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"
  xmlns:o="urn:schemas-microsoft-com:office:office"
  xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"
  xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math"
  xmlns:v="urn:schemas-microsoft-com:vml"
  xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"
  xmlns:w10="urn:schemas-microsoft-com:office:word"
  xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"
  xmlns:wne="http://schemas.microsoft.com/office/word/2006/wordml"
  mc:Ignorable="w14 wp14">
  <w:body>
    <w:p>
      <w:pPr><w:pStyle w:val="Title"/></w:pPr>
      <w:r><w:t>$escapedTitle</w:t></w:r>
    </w:p>
    <w:p>
      <w:pPr><w:pStyle w:val="Subtitle"/></w:pPr>
      <w:r>
        <w:rPr><w:color w:val="808080"/><w:sz w:val="20"/></w:rPr>
        <w:t xml:space="preserve">Category: $escapedCategory | Tags: $escapedTags | Date: $dateStr</w:t>
      </w:r>
    </w:p>
    <w:p><w:r><w:t xml:space="preserve"> </w:t></w:r></w:p>
    $contentParagraphs
    <w:p><w:r><w:t xml:space="preserve"> </w:t></w:r></w:p>
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr><w:color w:val="A0A0A0"/><w:sz w:val="16"/><w:i/></w:rPr>
        <w:t>Generated by Aura Study</w:t>
      </w:r>
    </w:p>
  </w:body>
</w:document>''';
  }

  static String _buildRelsXml() {
    return '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>''';
  }

  static String _buildContentTypesXml() {
    return '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>''';
  }

  static String _buildWordRelsXml() {
    return '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
</Relationships>''';
  }

  static String _escapeXml(String input) {
    return input
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&apos;');
  }

  static List<int> _createDocxZip(
    String documentXml,
    String relsXml,
    String contentTypesXml,
    String wordRelsXml,
  ) {
    // Build a proper ZIP file manually for DOCX format
    // This creates a minimal but valid DOCX that opens in Word/Google Docs
    final entries = <String, List<int>>{
      '[Content_Types].xml': _utf8Encode(contentTypesXml),
      '_rels/.rels': _utf8Encode(relsXml),
      'word/document.xml': _utf8Encode(documentXml),
      'word/_rels/document.xml.rels': _utf8Encode(wordRelsXml),
    };

    return _buildZip(entries);
  }

  static List<int> _utf8Encode(String text) {
    return const Utf8Encoder().convert(text);
  }

  /// Build a minimal ZIP archive from filename->bytes entries
  static List<int> _buildZip(Map<String, List<int>> entries) {
    final buffer = BytesBuilder();
    final centralDirectory = BytesBuilder();
    int offset = 0;

    for (final entry in entries.entries) {
      final nameBytes = const Utf8Encoder().convert(entry.key);
      final data = entry.value;

      // Calculate CRC32
      final crc = _crc32(data);

      // Local file header
      final localHeader = BytesBuilder();
      localHeader.add([0x50, 0x4B, 0x03, 0x04]); // Local file header signature
      localHeader.add(_uint16LE(20)); // Version needed
      localHeader.add(_uint16LE(0));  // General purpose bit flag
      localHeader.add(_uint16LE(0));  // Compression method (0 = stored)
      localHeader.add(_uint16LE(0));  // Last mod time
      localHeader.add(_uint16LE(0));  // Last mod date
      localHeader.add(_uint32LE(crc)); // CRC-32
      localHeader.add(_uint32LE(data.length)); // Compressed size
      localHeader.add(_uint32LE(data.length)); // Uncompressed size
      localHeader.add(_uint16LE(nameBytes.length)); // Filename length
      localHeader.add(_uint16LE(0));  // Extra field length
      localHeader.add(nameBytes);     // Filename
      localHeader.add(data);          // File data

      final localBytes = localHeader.toBytes();
      buffer.add(localBytes);

      // Central directory entry
      centralDirectory.add([0x50, 0x4B, 0x01, 0x02]); // Central directory signature
      centralDirectory.add(_uint16LE(20)); // Version made by
      centralDirectory.add(_uint16LE(20)); // Version needed
      centralDirectory.add(_uint16LE(0));  // General purpose bit flag
      centralDirectory.add(_uint16LE(0));  // Compression method
      centralDirectory.add(_uint16LE(0));  // Last mod time
      centralDirectory.add(_uint16LE(0));  // Last mod date
      centralDirectory.add(_uint32LE(crc)); // CRC-32
      centralDirectory.add(_uint32LE(data.length)); // Compressed size
      centralDirectory.add(_uint32LE(data.length)); // Uncompressed size
      centralDirectory.add(_uint16LE(nameBytes.length)); // Filename length
      centralDirectory.add(_uint16LE(0));  // Extra field length
      centralDirectory.add(_uint16LE(0));  // File comment length
      centralDirectory.add(_uint16LE(0));  // Disk number start
      centralDirectory.add(_uint16LE(0));  // Internal file attributes
      centralDirectory.add(_uint32LE(0));  // External file attributes
      centralDirectory.add(_uint32LE(offset)); // Relative offset
      centralDirectory.add(nameBytes);     // Filename

      offset += localBytes.length;
    }

    final centralDirBytes = centralDirectory.toBytes();
    final centralDirOffset = offset;
    buffer.add(centralDirBytes);

    // End of central directory record
    buffer.add([0x50, 0x4B, 0x05, 0x06]); // End of central directory signature
    buffer.add(_uint16LE(0));  // Disk number
    buffer.add(_uint16LE(0));  // Disk with central dir
    buffer.add(_uint16LE(entries.length)); // Entries on disk
    buffer.add(_uint16LE(entries.length)); // Total entries
    buffer.add(_uint32LE(centralDirBytes.length)); // Central dir size
    buffer.add(_uint32LE(centralDirOffset)); // Central dir offset
    buffer.add(_uint16LE(0));  // Comment length

    return buffer.toBytes();
  }

  static List<int> _uint16LE(int value) {
    return [value & 0xFF, (value >> 8) & 0xFF];
  }

  static List<int> _uint32LE(int value) {
    return [
      value & 0xFF,
      (value >> 8) & 0xFF,
      (value >> 16) & 0xFF,
      (value >> 24) & 0xFF,
    ];
  }

  /// Standard CRC32 computation
  static int _crc32(List<int> data) {
    int crc = 0xFFFFFFFF;
    for (final byte in data) {
      crc ^= byte;
      for (int i = 0; i < 8; i++) {
        if (crc & 1 == 1) {
          crc = (crc >> 1) ^ 0xEDB88320;
        } else {
          crc >>= 1;
        }
      }
    }
    return crc ^ 0xFFFFFFFF;
  }
}
